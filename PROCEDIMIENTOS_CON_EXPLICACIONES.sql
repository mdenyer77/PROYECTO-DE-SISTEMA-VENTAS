-- PROCEDIMIENTO 1: sp_ListarVentasConCliente
-- ???????????????????????????????????????????????????????????????????????????????
-- 
-- QUÉ HACE:
--   Obtiene todas las ventas juntas con la información del cliente
--   Usa INNER JOIN para unir: Ventas + Cliente
--   Devuelve datos legibles (nombres en lugar de IDs)
--
-- DÓNDE CONECTA:
--   Base de Datos: Ventas
--   Tabla 1: Ventas (v)
--   Tabla 2: Cliente (c)
--   Relación: v.ID_cliente = c.ID_cliente
--
-- DÓNDE SE USA:
--   Form3.cs (Facturas) - En método CargarVentas()
--   Form4.cs (Ventas) - En método CargarVentas()
--   Se llama desde: VentaDetalleBL.ListarVentasConCliente()
--
-- DATOS QUE DEVUELVE:
--   Fecha_venta           (Fecha de la venta)
--   Cliente_Nombre        (Nombre del cliente - de tabla Cliente)
--   Cliente_Telefono      (Teléfono del cliente)
--   Cliente_Direccion     (Dirección del cliente)
--   Total_general         (Monto total de la venta)
--   Estado_venta          (Activa o Cancelada)
--
-- QUÉ MUESTRA EN EL DATAGRID:
--   Fecha | Cliente | Teléfono | Dirección | Total | Estado
--
-- ???????????????????????????????????????????????????????????????????????????????

CREATE PROCEDURE sp_ListarVentasConCliente
AS
BEGIN
    SELECT 
        v.Fecha_venta,
        c.Nombre AS Cliente_Nombre,
        c.Telefono AS Cliente_Telefono,
        c.Direccion AS Cliente_Direccion,
        v.Total_general,
        CASE WHEN v.Estado_venta = 1 THEN 'Activa' ELSE 'Cancelada' END AS Estado_venta
    FROM Ventas v
    INNER JOIN Cliente c ON v.ID_cliente = c.ID_cliente
    ORDER BY v.Fecha_venta DESC
END
GO

