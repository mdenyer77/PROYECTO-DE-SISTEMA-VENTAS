-- PROCEDIMIENTO 3: sp_ListarDetalleVentaCompleto
-- ???????????????????????????????????????????????????????????????????????????????
--
-- QUÉ HACE:
--   Obtiene todos los detalles (items) de una venta específica
--   Usa INNER JOIN para unir: Detalle_Venta + Productos + Categoria
--   Muestra información completa de cada producto en la venta
--
-- DÓNDE CONECTA:
--   Base de Datos: Ventas
--   Tabla 1: Detalle_Venta (dv)
--   Tabla 2: Productos (p)
--   Tabla 3: Categoria (c)
--   Relaciones: 
--     dv.ID_producto = p.ID_Producto
--     p.ID_categoria = c.ID_Categoria
--
-- DÓNDE SE USA:
--   Se puede usar en un futuro para mostrar detalles de una venta seleccionada
--   Se llama desde: VentaDetalleBL.ListarDetalleVentaCompleto(idVenta)
--
-- PARÁMETRO DE ENTRADA:
--   @ID_venta INT - El ID de la venta de la que queremos ver los detalles
--
-- DATOS QUE DEVUELVE:
--   Producto_Nombre       (Nombre del producto - de tabla Productos)
--   Categoria_Nombre      (Nombre de la categoría - de tabla Categoria)
--   Cantidad              (Cantidad del producto en esta venta)
--   Precio_Unitario       (Precio a pagar por unidad)
--   Subtotal              (Cantidad * Precio = Subtotal del item)
--
-- QUÉ MUESTRA EN EL DATAGRID:
--   Producto | Categoría | Cantidad | Precio Unit. | Subtotal
--
-- EJEMPLO DE USO EN SQL:
--   EXEC sp_ListarDetalleVentaCompleto @ID_venta = 1
--   (Esto devolvería todos los productos de la venta #1)
--
-- ???????????????????????????????????????????????????????????????????????????????

CREATE PROCEDURE sp_ListarDetalleVentaCompleto
    @ID_venta INT
AS
BEGIN
    SELECT 
        p.Nombre_Producto AS Producto_Nombre,
        c.Nombre_Categoria AS Categoria_Nombre,
        dv.Cantidad,
        dv.Precio AS Precio_Unitario,
        (dv.Cantidad * dv.Precio) AS Subtotal
    FROM Detalle_Venta dv
    INNER JOIN Productos p ON dv.ID_producto = p.ID_Producto
    INNER JOIN Categoria c ON p.ID_categoria = c.ID_Categoria
    WHERE dv.ID_venta = @ID_venta
    ORDER BY dv.ID_detalle_venta
END
GO

