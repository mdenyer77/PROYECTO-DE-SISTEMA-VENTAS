-- PROCEDIMIENTO 2: sp_ListarProductosConCategoria
-- ???????????????????????????????????????????????????????????????????????????????
--
-- QUÉ HACE:
--   Obtiene todos los productos juntos con el nombre de su categoría
--   Usa INNER JOIN para unir: Productos + Categoria
--   Devuelve datos legibles (nombre de categoría en lugar de ID)
--
-- DÓNDE CONECTA:
--   Base de Datos: Ventas
--   Tabla 1: Productos (p)
--   Tabla 2: Categoria (c)
--   Relación: p.ID_categoria = c.ID_Categoria
--
-- DÓNDE SE USA:
--   Form2.cs (Productos) - En método CargarProductos()
--   Se llama desde: ProductoDetalleBL.ListarProductosConCategoria()
--
-- DATOS QUE DEVUELVE:
--   Nombre_Producto       (Nombre del producto)
--   Categoria_Nombre      (Nombre de la categoría - de tabla Categoria)
--   Precio_Producto       (Precio unitario)
--   Stock                 (Cantidad disponible)
--
-- QUÉ MUESTRA EN EL DATAGRID:
--   Producto | Categoría | Precio | Stock
--
-- ???????????????????????????????????????????????????????????????????????????????

CREATE PROCEDURE sp_ListarProductosConCategoria
AS
BEGIN
    SELECT 
        p.Nombre_Producto,
        c.Nombre_Categoria AS Categoria_Nombre,
        p.Precio_Producto,
        p.stock AS Stock
    FROM Productos p
    INNER JOIN Categoria c ON p.ID_categoria = c.ID_Categoria
    ORDER BY p.Nombre_Producto
END
GO

